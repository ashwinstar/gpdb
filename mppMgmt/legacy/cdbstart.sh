#!/bin/bash
# ---------------------------------------------------------------------
#
# cdbstart
#
#       Starts the listener(s) of a the CDB cluster.
#
# $Id$
# ---------------------------------------------------------------------

PATH="$(dirname $0):$PATH"

usage="[ PGROOT=<root_directory> ] $(basename $0) \n        [ {--dbroot|-D} <root_directory> ] \n        [ --stats {off|on|all|{command,block,row} ] \n        [ {--prefix|-P} { dbprefix | cdb} ] \n        [ {-u} {--help} ]"

echo -e "cdbstart: Starts the listener(s) of the local CDB cluster."
echo -e "Copyright (c) 2004-2005 Metapa, Inc. All Rights Reserved"

function display_help
{
    echo -e "\nSyntax: $usage"

    echo -e "\nThis command starts the listener(s) of the local CDB cluster. The"
    echo    "CDB cluster must have been previously initialized using \"cdbinitdb\"."

    echo -e "\nIf \$PGROOT is not set, or --dbroot or -D are not passed, the location "
    echo    "containing the data directories of the CDB cluster to start defaults "
    echo -e "to \"\$HOME/cdb-data\". You can control which databases are started by "
    echo -e "passing the --prefix option on the command line. If it is not specified,"
    echo -e "it defaults \"cdb\""

    echo -e "\nThe PostgreSQL statistics collector can be enabled using the --stats option."
    echo -e "    --stats=off disables the statistics collector. "
    echo -e "    --stats=on  turns on the statistics collector but does not enable generation "
    echo    "      of the command, block, or row statistics."
    echo    "    --stats=all turns on the statistics collector and enables all statistics "

    echo -e "\nThe statistics collector can be turned on and selected statistics generated by "
    echo    "specifying one or more of command, block, and row (use commas for separation)."

    echo -e "\nServer logs are written to '\$PGROOT/logfile.\$DBNAME' where \$DBNAME "
    echo    "is discovered from the directories in \$PGROOT.  Debug level is set to 4 and the"
    echo    "TCP socket listener is enabled."

    echo -e "\nUse \"cdbpsql <databasename>\" to interact with the first segDB of the CDB cluster."
    echo -e "If you need use the -u option, you can start the whole cluster in utility mode."

    echo -e "\nSee README.txt for more details.\n"

    exit 1
}


# - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
#
# Pick out command line arguments:
#
#     -D | --dbroot     <root_directory>        $PGROOT
#          --stats      off|on|{command,block,row}
#     -P | --prefix     <dbname prefix>
#
# - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

# Some useful variables
positional=0
options_ended=
dbroot=
stats=
prefix=
utility=

# Loop through our command line args, and see what we have
# TODO: Figure out why we don't trap bad options in the first block
while [ $# -gt 0 ]
do
    if [ ! $options_ended ]; then
        OPTIND=1
        OPTARG='--'
        while getopts :D:P:u option
        do
            case $option in
                :)
                   echo "$(basename $0): Option '$OPTARG' requires a value" >&2
                   exit 1
                   ;;
                \?)
                   # This case is hit for the first long option or argument.
                   [ "$OPTARG" != "?" ] && break
                   ;;
                D)
                   dbroot="$OPTARG"
                   ;;
                P)
                   prefix="$OPTARG"
                   ;;
                u)
                   utility="-c cdb_session_role=utility"
                   ;;
                *)
                   display_help
                   exit 1
                   ;;
            esac
            OPTARG='--'
        done

        #
        # If we get here with options consumed and OPTARG set to '--'
        # we've hit the "options end" token '--'.  Prepare NOT to
        # return through options processing.
        #
        if [ "$OPTARG" = "--" -a $OPTIND -gt 0 ]; then
            options_ended=true
        fi

        unset option
        shift $(($OPTIND - 1))
    fi

    #
    # Handle long options and positional parameters
    #
    if [ $# -gt 0 ]; then
        val="$(expr "$1" : '--[^=]*=\(.*\)')"
        case "$1" in
            --help)
                display_help
                exit 1
                ;;
            --dbroot)
                dbroot=${2:?Option '--dbroot' requires a value}
                shift 2
                ;;
            --dbroot=*)
                dbroot=${val:?Option '--dbroot' requires a value}
                shift 1
                ;;
            --prefix)
                prefix=${2:?Option '--prefix' requires a value}
                shift 2
                ;;
            --prefix=*)
                prefix=${val:?Option '--prefix' requires a value}
                shift 1
                ;;
            --stats)
                stats=${2:?Options '--stats' requires a value}
                shift 2
                ;;
            --stats=*)
                stats=${val:?Option '--stats' requires a value}
                shift 1
                ;;
            --*)
                echo "$(basename $0): Unrecognized option \"$1\"" >&2
                exit 1
                ;;
            *)
                positional=$((positional + 1))
                case $positional in
                    *)
                        echo "Unrecognized argument(s) beginning with $1" >&2
                        exit 1
                        ;;
                esac
                shift 1
                ;;
        esac
    fi

done

# - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
# Now that all the options and arguments have been parsed out, ensure
# that we have everthing that is required.
# - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

PGROOT=${dbroot:-$PGROOT}
: ${PGROOT:=$HOME/cdb-data}

# And what about our prefix?
prefix=${prefix:-$prefix}
: ${prefix:=cdb}

declare -a stats_options
function stats_append
{
    local i=${#stats_options[@]}
    stats_options[$((i++))]="-c"
    stats_options[$i]="$1"
    return
}
if [ "$stats" ]; then
    case $stats in
        all)
            stats_append "stats_start_collector=on"
            stats_append "stats_command_string=on"
            stats_append "stats_block_level=on"
            stats_append "stats_row_level=on"
            ;;
        on)
            stats_append "stats_start_collector=on"
            ;;
        off)
            stats_append "stats_start_collector=off"
            ;;
        *)
            stats_append "stats_start_collector=on"
            for option in $(echo "$stats" | tr ',' ' ')
            do
                case $option in
                    command)
                        stats_append "stats_command_string=on"
                        ;;
                    block)
                        stats_append "stats_block_level=on"
                        ;;
                    row)
                        stats_append "stats_row_level=on"
                        ;;
                    off | on )
                        echo "Statistics option \"$option\" is only supported alone" >&2
                        exit 2
                        ;;
                    *)  echo "Unsupported statistics option \"$option\"" >&2
                        exit 2
                        ;;
                esac
            done
            ;;
    esac
fi
unset -f stats_append

source cdbfuncs

# Discard outside values of these
unset PGHOST
unset PGHOSTADDR

# The following vary depending on the target node
export PGDATA
export PGPORT


# ---------------------------------------------------------------------
# Start the DB instances
# ---------------------------------------------------------------------
shopt -s extglob

for PGDATA in "$PGROOT"/$prefix*[0-9]?([0-9])
do
    [ ! -d "$PGDATA" ] && continue

    db=$(basename "$PGDATA")
    PGPORT=$(getPort)

    echo "Starting DB instance ($PGDATA at $PGPORT)"
    echo "The logfile can be found at $PGROOT/logfile.$db"

    pg_ctl -l "$PGROOT"/logfile.$db -o "-B 16 -d 4 -i ${stats_options[@]} $utility" start
done

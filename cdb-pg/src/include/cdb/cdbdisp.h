#ifndef CDBDISP_H
#define CDBDISP_H

#include "executor/execdesc.h"



/*
 * CdbDispatchResult:
 * Struct for holding the result information
 * for a command dispatched by CdbCommandDispatch to
 * a single segdb.
 */
typedef struct CdbDispatchResult
{
	struct segment_database_descriptor *segdbDesc;		/* The
														 * SegmentDatabaseDescrip
														 * tor for the segdb
														 * that the command ran
														 * on */
	char	   *error_message;	/* The error message generated by the command
								 * on the segdb */
	int			cmdTuples;		/* The value of PQcmdTuples (as an int) for
								 * the command on the segdb */
	char	   *cmdStatus;		/* The value of PQcmdStatus for the command on
								 * the segdb */
	int			resultStatus;	/* The value of PQresultStatus for the command
								 * on the segdb */								 
	bool		isPrimary;      /* If this is a primary gang member */
}	CdbDispatchResult;

/*
 * CdbDispatchResults:
 * Struct for holding the results information for all segdb's
 * that the command was sent to,  for a command dispatched by CdbCommandDispatch
 */
typedef struct CdbDispatchResults
{
	bool		success;
	int			count;
	char	   *szCommand;
	CdbDispatchResult *pResults;
}	CdbDispatchResults;

/*
 * CdbDispatchCommand:
 * Send ths szCommand SQL statement to the subset of all segdbs in the cluster, or,
 * If CdbDispatchCommandIntEnumeriaction is called,
 * then the segdbList parameter points to an array of SegmentDatabaseDescriptor*'s
 * to send the command to, with lenght segdbListCount.
 * The cancelFromBelow indicates whether an error
 * occurring on one of the qExec segdbs should cause all still-executing commands to cancel
 * on other qExecs. Normally this would be true.  The commands are run inside of threads.
 * The number of segdbs handled by any one thread is determined by the
 * guc variable mpp_connections_per_thread.
 */
extern void CdbDispatchCommand(const char *szCommand, bool cancelFromBelow);

extern void CdbDispatchCommandInt(const char *szCommand, bool cancelFromBelow,
					  void ***resultSets);

extern void
CdbDispatchCommandIntEnumeration(const char *szCommand,
								 struct segment_database_descriptor
								 ** segdbList, int segdbListCount,
								 bool cancelFromBelow, void ***resultSets);

extern void
CdbDispatchToGang(const char *szCommand, struct Gang * gp,
				  bool cancelFromBelow, void ***resultSets);

/*
 * CdbCheckDispatchResult:
 * Waits for threads that were launched in CdbDispatchCommand
 * to finish, and then checks to see whether they all succeeded.
 * Returns a pointer to a CdbDispatchResults struct.  This struct is allocated
 * by CdbCheckDispatchResult.	Caller should call DestroyCdbDispatchResults
 * on this pointer to pfree all the memory.
 */
extern CdbDispatchResults *CdbCheckDispatchResult(void);

extern CdbDispatchResults *CdbCheckDispatchResultInt(void ***, int *);

/*
 * CdbDumpDispatchResults:
 * Formats a string with results info.
 * If verbose = true, reports on all target databases.
 * If false, reports on only failures.
 */
extern char *CdbDumpDispatchResults(CdbDispatchResults * results, bool verbose);

/*
 * DestroyCdbDispatchResults:
 * pfrees all memory allocated in CdbDispatchResults struct.
 */
extern void DestroyCdbDispatchResults(CdbDispatchResults * results);


/*
 * SumCmdTuples:
 * Accumulates the cmdTuples over all CdbDispatchResult structs.
 */
extern int	SumCmdTuples(CdbDispatchResults * results);


/*
 * CdbDoCommand:
 * Combination of CdbDispatchCommand and then CdbCheckDispatchResult.
 * If it fails on any of the targets, then the undo command is run
 * on any targets that were successful.
 * If it successfully ran, returns true.
 * If it failed on at least one target, and the undo was successful, then returns false.
 * If it failed but the undo failed, ereport is called.
 */
extern bool CdbDoCommand(const char *szCommand, bool cancelFromBelow);

extern bool CdbDoCommandInt(const char *szCommand,
				bool cancelFromBelow, void ***resultSets);


extern void CdbDispatchPlan(QueryDesc *queryDesc);


#endif   /* CDBDISP_H */

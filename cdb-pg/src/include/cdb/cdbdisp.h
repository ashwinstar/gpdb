#ifndef CDBDISP_H
#define CDBDISP_H


/*
 * Enumeration for defining the target subset of all segdbs 
 * to send a command to.  This is determined by considering the
 * "scope" of a command.  For example, 
 * 		1) a create user command has listener scope. Use DTS_LISTENER
 * 		2) A create table command has database scope, and should include
 * 			secondaries as well as primaries.  Use DTS_SEGDB.
 * 		3) A select stament would have database scope but only one per segindex.
 * 			Use DTS_SEGMENT.
 */
typedef enum
{
	DTS_SEGDB,		/* Send to all connected segdbs */
	DTS_SEGMENT,	/* Send to only one segdb per segindex */
	DTS_LISTENER	/* Send ot only one segdb per listener */
} DispatchTargetSet;


/*
 * CdbDispatchResult:
 * Struct for holding the result information
 * for a command dispatched by CdbCommandDispatch to
 * a single segdb.
 */
typedef struct CdbDispatchResult
{
	int				segindex;		/* The segindex of the segdb */
	bool			isprimary;		/* The isprimary flag of the segdb */
	char			*error_message; /* The error message generated by the command on the segdb */
	int				cmdTuples;		/* The value of PQcmdTuples (as an int) for the command on the segdb */
	char			*cmdStatus;		/* The value of PQcmdStatus for the command on the segdb */
	int				resultStatus;
} CdbDispatchResult;

/*
 * CdbDispatchResults:
 * Struct for holding the results information for all segdb's
 * that the command was sent to,  for a command dispatched by CdbCommandDispatch
 */
typedef struct CdbDispatchResults
{
	bool				success;
	int					count;
	CdbDispatchResult	*pResults;
} CdbDispatchResults;



/*
 * CdbDispatchCommand:
 * Send ths szCommand SQL statement to the subset of all segdbs in the cluster
 * specified by the targetSet parameter.  cancelFromBelow indicates whether an error
 * occurring on one of the qExec segdbs should cause all still-executing commands to cancel
 * on other qExecs. Normally this would be true.  The commands are sent over the libpq
 * connections that were established during cdblink_setup.  They are run inside of threads.
 * The number of segdbs handled by any one thread is determined by the
 * guc variable cdb_connections_per_thread.
 */
extern void CdbDispatchCommand( const char *szCommand, DispatchTargetSet targetSet, bool cancelFromBelow );

/*
 * CdbCheckDispatchResult:
 * Waits for threads that were launched in CdbDispatchCommand
 * to finish, and then checks to see whether they all succeeded.
 * Returns a pointer to a CdbDispatchResults struct.  This struct is allocated
 * by CdbCheckDispatchResult.   Caller should call DestroyCdbDispatchResults
 * on this pointer to pfree all the memory.
 */
extern CdbDispatchResults* CdbCheckDispatchResult(void);

/*
 * DestroyCdbDispatchResults:
 * pfrees all memory allocated in CdbDispatchResults struct.
 */
extern void DestroyCdbDispatchResults(CdbDispatchResults *results);


/*
 * SumCmdTuples:
 * Accumulates the cmdTuples over all CdbDispatchResult structs.
 */
extern int SumCmdTuples(CdbDispatchResults *results);




#endif	/* CDBDISP_H */

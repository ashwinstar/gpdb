#include <gpcc.h>
#include "enum.h"

#define CASESTR(x)  case x: return APR_STRINGIFY(x)

const char* msg_str(msg_t msg)
{
    switch (msg) {
	CASESTR(NULL_MSG);
	CASESTR(GET_IDENTITY_MSG);
	CASESTR(IDENTITY_MSG);
	CASESTR(KEEP_ALIVE_MSG);
	CASESTR(VOTE_ME_MSG);
	CASESTR(VOTE_REPLY_MSG);
	CASESTR(CSN_GET_MSG);
	CASESTR(CSN_REPLY_MSG);
	CASESTR(CONFIG_GET_MSG);
	CASESTR(CONFIG_REPLY_MSG);
	CASESTR(LEADMA_GET_MSG);
	CASESTR(LEADMA_REPLY_MSG);
	CASESTR(SEGMENT_REQUEST_MSG);
	CASESTR(SEGMENT_REPLY_MSG);
	CASESTR(HOST_REQUEST_MSG);
	CASESTR(ARRAY_REQUEST_MSG);
	CASESTR(ARRAY_REPLY_MSG);
	CASESTR(STATUS_REQUEST_MSG);
	CASESTR(STATUS_REPLY_MSG);
	CASESTR(ALERT_MSG);
	CASESTR(ERROR_MSG);
    case MSG_MAX: break;
    }
    return "UNKNOWN_MSG";
}


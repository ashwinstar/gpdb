#define CASESTR(x)  case x: return APR_STRINGIFY(x)

const char* msg_str(msg_t msg)
{
    switch (msg) {
	CASESTR(NULL_MSG);
	CASESTR(LMA_VOTE_ME_MSG);
	CASESTR(LMA_VOTE_YES_MSG);
	CASESTR(LMA_VOTE_NO_MSG);
	CASESTR(LMA_VOTE_WIN_MSG);
	CASESTR(LMA_VOTE_LOST_MSG);
	CASESTR(LMA_LEADMA_MSG);
	CASESTR(LMA_CONFIG_MSG);
	CASESTR(SEGMENT_REQUEST_MSG);
	CASESTR(SEGMENT_REPLY_MSG);
	CASESTR(STATUS_REQUEST_MSG);
	CASESTR(STATUS_REPLY_MSG);
	CASESTR(ALERT_MSG);
	CASESTR(ERROR_MSG);
    case MSG_MAX: break;
    }
    return "UNKNOWN_MSG";
}



